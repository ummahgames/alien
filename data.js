export const TOTAL_MISSIONS = 42;
export function getMission(index) {
  const planet = PLANETS[Math.floor(index / 7)],
    number = index % 7;
  if (!planet || number < 0) throw new RangeError("Unknown mission");
  return {
    ...planet.missions[number],
    planet,
    number,
    index,
    id: `${planet.id}-${number + 1}`,
    seed: `agency-v${VERSION}-${planet.id}-${number + 1}`,
  };
}
